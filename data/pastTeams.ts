import type { Member } from "@/data/team";

export type PastMember = Pick<Member, "name" | "role" | "track" | "linkedin" | "photo">;

export type PastTeam = {
  season: "Winter" | "Spring" | "Fall";
  year: number;
  members: PastMember[];
};

/** Pass `null` as photo when the person has no headshot; the card shows their initials */
const p = (name: string, role: string, track: Member["track"], photo?: null): PastMember => ({
  name,
  role,
  track,
  ...(photo === null ? { photo } : {}),
});

export function termLabel(team: Pick<PastTeam, "season" | "year">) {
  return `${team.season} ${team.year}`;
}

/** URL segment for /team/[term], e.g. winter-2026 */
export function termSlug(team: Pick<PastTeam, "season" | "year">) {
  return `${team.season.toLowerCase()}-${team.year}`;
}

/**
 * Group photos per term, under /public/images as team-<term>.jpg, then
 * team-<term>-2.jpg for a second shot. Terms not listed have no group photo.
 */
const groupPhotoCounts: Record<string, number> = {
  "winter-2026": 1,
  "fall-2025": 1,
  "spring-2025": 1,
  "winter-2025": 1,
  "fall-2024": 1,
  "spring-2024": 2,
  "winter-2024": 1,
  "fall-2023": 1,
  "spring-2023": 1,
  "winter-2023": 1,
  "winter-2020": 1,
  "fall-2019": 1,
  "spring-2019": 1,
  "winter-2019": 1,
};

export function groupPhotosFor(team: Pick<PastTeam, "season" | "year">) {
  const slug = termSlug(team);
  return Array.from({ length: groupPhotoCounts[slug] ?? 0 }, (_, i) => ({
    src: `/images/team-${slug}${i === 0 ? "" : `-${i + 1}`}.jpg`,
    alt: `The ${termLabel(team)} Student Investment Fund team`,
  }));
}

